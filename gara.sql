CREATE TABLE PHIEUSUAXE (
    MaPSX CHAR(10) PRIMARY KEY,
    MaTN CHAR(10),
    MaNV CHAR(10),
    NgaySua DATETIME,
    FOREIGN KEY (MaTN) REFERENCES PHIEUTIEPNHAN(MaTN),
    FOREIGN KEY (MaNV) REFERENCES NHANVIEN(MaNV)
);

CREATE TABLE PHIEUSUACT (
    MaPSX CHAR(10),
    MaPT CHAR(10),
    NoiDung CHAR(255),
    TienCong FLOAT,
    DonGia FLOAT,
