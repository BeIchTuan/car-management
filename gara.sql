CREATE DATABASE GaraDB;

USE GaraDB;

CREATE TABLE LOAIPT (
    MaLoai CHAR(10) PRIMARY KEY,
    TenLoai CHAR(100)
);

CREATE TABLE NHACUNGCAP (
    MaNCC CHAR(10) PRIMARY KEY,
    TenNCC CHAR(80),
    SDT CHAR(12),
    DiaChi CHAR(80)
);

CREATE TABLE NHANVIEN (
    MaNV CHAR(10) PRIMARY KEY,
    HoTen CHAR(50),
    GioiTinh CHAR(10),
    CCCD CHAR(12),
    DiaChi CHAR(80),
    SDT CHAR(10),
    Quyen INT
);
ALTER TABLE NHANVIEN ADD IsDeleted TINYINT(1) DEFAULT 0;
ALTER TABLE NHANVIEN
ALTER COLUMN Quyen SET DEFAULT 0;

CREATE TABLE PHIEUNHAP (
    MaPN CHAR(10) PRIMARY KEY,
    MaNV CHAR(10),
    MaNCC CHAR(10),
    NgayLapPhieu DATETIME,
    FOREIGN KEY (MaNV) REFERENCES NHANVIEN(MaNV),
    FOREIGN KEY (MaNCC) REFERENCES NHACUNGCAP(MaNCC)
);

CREATE TABLE PHUTUNG (
    MaPT CHAR(10) PRIMARY KEY,
    MaLoai CHAR(10),
    TenPT CHAR(80),
    DVT CHAR(20),
    GiaThamKhao FLOAT,
    FOREIGN KEY (MaLoai) REFERENCES LOAIPT(MaLoai)
);

CREATE TABLE PHIEUNHAPCT (
    MaPN CHAR(10),
    MaPT CHAR(10),
    DonGia FLOAT,
    SoLuong INT,
    PRIMARY KEY (MaPN, MaPT),
    FOREIGN KEY (MaPN) REFERENCES PHIEUNHAP(MaPN),
    FOREIGN KEY (MaPT) REFERENCES PHUTUNG(MaPT)
);

CREATE TABLE BANGTONKHO (
    MaTK CHAR(10),
    MaPT CHAR(10),
    GhiChu CHAR(255),
    PRIMARY KEY (MaTK, MaPT),
    FOREIGN KEY (MaPT) REFERENCES PHUTUNG(MaPT)
);

CREATE TABLE ChuXe (
    MaCX CHAR(10) PRIMARY KEY,
    HoTen CHAR(50),
    DiaChi CHAR(80),
    SDT CHAR(10)
