CREATE TABLE XE (
    MaBX CHAR(10) PRIMARY KEY,
    MaCX CHAR(10),
    MaHX CHAR(10),
    MoTa CHAR(255),
    FOREIGN KEY (MaCX) REFERENCES ChuXe(MaCX),
    FOREIGN KEY (MaHX) REFERENCES HIEUXE(MaHX)
